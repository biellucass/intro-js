// Os operadores aritméticos são utilizados parra realizar operações matemáticas, como por exemplo, somar, subtrair, multiplicar e dividir.

let preco = 50;
let frete = 15;
let cupomDesconto = 30;

// 1 - Adição ( + )
console.log("Exemplo de Adição:");
console.log(preco + frete);

const soma = preco + frete;
console.log(soma);
console.log("----------------");

// 2 - Subtração ( - )
console.log("Exemplo de subtração:");
console.log(soma - cupomDesconto);
console.log("----------------");

// 3 - Multiplicação ( * )
console.log("Exemplo de Multiplicação:");
const multiplicacao = preco * frete;
console.log(multiplicacao);
console.log(10 * 20);
console.log("----------------");

// 4 - Divisão ( / )
console.log("Exemplo de Divisão:");
const divisao = soma / 4;
console.log(divisao);
console.log(100 / 20);
console.log(10 / 0);
console.log("----------------");

// 5 - Resto ( : )
console.log("Exemplo de Resto:");
const resto = soma % 4;
console.log(resto);
console.log(100 % 20);
console.log(10 % 4);
console.log("----------------");

// 6 - Exponenciação ( ** )
const exponenciacao = preco ** frete;
console.log("Exemplo de Exponenciação:");
console.log(exponenciacao);
console.log(2 ** 3);
console.log(5 ** 2);
console.log("----------------");




